export interface SocialLinksProps {
  /** Array of social link entries. */
  links: SocialLink[]
  /** Layout direction. */
  direction?: "horizontal" | "vertical"
  /** Show platform name labels. */
  showLabels?: boolean
  /** Additional CSS classes. */
  className?: string
}

/** Displays a row or column of social media link buttons with platform icons. */
export function SocialLinks({
  links,
  direction = "horizontal",
  showLabels = false,
  className,
}: SocialLinksProps) {
  if (links.length === 0) return null

  return (
    <div
      className={cn(
        "flex gap-1.5",
        direction === "vertical" ? "flex-col" : "flex-row flex-wrap",
        className
      )}
    >
      {links.map((link) => {
        const meta = platformMeta[link.platform]
        if (!meta) return null

        return showLabels ? (
          <Button
            key={link.platform}
            variant="outline"
            size="sm"
            className="gap-2 justify-start"
            asChild
          >
            <a href={link.url} target="_blank" rel="noopener noreferrer">
              {meta.icon}
              {link.label ?? meta.name}
            </a>
          </Button>
        ) : (
          <Button
            key={link.platform}
            variant="ghost"
            size="icon-sm"
            asChild
            aria-label={link.label ?? meta.name}
          >
            <a href={link.url} target="_blank" rel="noopener noreferrer">
              {meta.icon}
            </a>
          </Button>
        )
      })}
    </div>
  )
}
